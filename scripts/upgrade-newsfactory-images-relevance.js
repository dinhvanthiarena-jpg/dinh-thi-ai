require('dotenv').config();
const fs = require('fs');
const path = require('path');
const connectDB = require('../config/db');
const BlogPost = require('../models/BlogPost');
const { fetchStockImage, suggestImageQuery } = require('../services/newsFactoryService');

const AUTO_IMAGE_DIR = path.join(__dirname, '..', 'public', 'images', 'blog', 'auto');
const CREDIT_PATTERN = /<p class="text-xs text-muted italic">Ảnh:[\s\S]*?<\/p>/;

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function replaceCredit(content, newCreditHtml) {
  if (CREDIT_PATTERN.test(content)) {
    return content.replace(CREDIT_PATTERN, newCreditHtml);
  }
  return `${content}\n${newCreditHtml}`;
}

async function run() {
  await connectDB();

  const posts = await BlogPost.findAll({ where: { isAutoGenerated: true }, order: [['createdAt', 'ASC']] });
  const usedImages = await BlogPost.findAll({
    where: { coverImageSourceId: { [require('sequelize').Op.ne]: null } },
    attributes: ['coverImageSourceId'],
  });
  const usedPageIds = new Set(usedImages.map((p) => p.coverImageSourceId));

  let upgraded = 0;
  let skipped = 0;
  for (const post of posts) {
    const imageQuery = await suggestImageQuery(post.title);
    const stockImage = await fetchStockImage(post.category, usedPageIds, imageQuery);

    if (!stockImage || stockImage.sourceId === post.coverImageSourceId) {
      skipped += 1;
      console.log('bỏ qua (không tìm được ảnh tốt hơn):', post.title);
      await sleep(300);
      continue;
    }

    const oldUrl = post.coverImageUrl;
    const newContent = replaceCredit(post.content, `<p class="text-xs text-muted italic">${stockImage.credit}</p>`);
    await post.update({
      coverImageUrl: stockImage.url,
      coverImageSourceId: stockImage.sourceId,
      content: newContent,
    });
    usedPageIds.add(stockImage.sourceId);

    // Dọn file ảnh local cũ nếu có (tránh rác trong public/images/blog/auto/).
    if (oldUrl && oldUrl.startsWith('/images/blog/auto/')) {
      const oldPath = path.join(__dirname, '..', 'public', oldUrl.replace(/^\//, ''));
      fs.unlink(oldPath, () => {});
    }

    upgraded += 1;
    console.log('đã nâng cấp ảnh cho:', post.title);
    await sleep(300);
  }

  console.log(`Xong — đã nâng cấp ${upgraded} bài, giữ nguyên ${skipped} bài.`);
  process.exit(0);
}

run().catch((err) => {
  console.error('lỗi:', err.message);
  process.exit(1);
});
