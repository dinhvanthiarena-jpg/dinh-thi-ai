/**
 * Các bài tự động đã lỡ dùng chung 1 icon SVG cố định mỗi chuyên mục (trước
 * khi có nhiều mẫu) — script này gán lại ngẫu nhiên trong 3 mẫu cho từng bài,
 * để cùng 1 chuyên mục không hiện y hệt 1 icon liên tiếp nhau nữa.
 * Chạy 1 lần trên máy chủ:
 *   source ~/nodevenv/dinh-thi-ai/20/bin/activate
 *   node scripts/randomize-existing-svg-covers.js
 */
require('dotenv').config();
const connectDB = require('../config/db');
const BlogPost = require('../models/BlogPost');

const CATEGORY_COVER_VARIANTS = {
  'ai-cong-nghe': ['cat-ai-cong-nghe.svg', 'cat-ai-cong-nghe-b.svg', 'cat-ai-cong-nghe-c.svg'],
  'xu-huong': ['cat-xu-huong.svg', 'cat-xu-huong-b.svg', 'cat-xu-huong-c.svg'],
  'dao-tao-nghe-nghiep': ['cat-dao-tao-nghe-nghiep.svg', 'cat-dao-tao-nghe-nghiep-b.svg', 'cat-dao-tao-nghe-nghiep-c.svg'],
  'kinh-doanh': ['cat-kinh-doanh.svg', 'cat-kinh-doanh-b.svg', 'cat-kinh-doanh-c.svg'],
  'doi-song': ['cat-doi-song.svg', 'cat-doi-song-b.svg', 'cat-doi-song-c.svg'],
  'giai-tri': ['cat-giai-tri.svg', 'cat-giai-tri-b.svg', 'cat-giai-tri-c.svg'],
};

async function run() {
  await connectDB();

  const posts = await BlogPost.findAll({ where: { isAutoGenerated: true } });
  let changed = 0;
  for (const post of posts) {
    if (!post.coverImageUrl || !post.coverImageUrl.startsWith('/images/blog/cat-')) continue; // ảnh thật, bỏ qua
    const variants = CATEGORY_COVER_VARIANTS[post.category];
    if (!variants) continue;
    const newFile = variants[Math.floor(Math.random() * variants.length)];
    const newUrl = `/images/blog/${newFile}`;
    if (newUrl === post.coverImageUrl) continue;
    await post.update({ coverImageUrl: newUrl });
    changed += 1;
  }

  console.log(`Xong — đã đổi icon cho ${changed} bài.`);
  process.exit(0);
}

run().catch((err) => {
  console.error('lỗi:', err.message);
  process.exit(1);
});
