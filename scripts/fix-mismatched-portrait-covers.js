require('dotenv').config();
const fs = require('fs');
const path = require('path');
const connectDB = require('../config/db');
const BlogPost = require('../models/BlogPost');
const { Op } = require('sequelize');

const PERSON_PORTRAIT_PATTERN =
  /\b(president|politician|prime minister|minister of|foreign minister|chancellor|monarch|king of|queen of|senator|governor|diplomat|portrait of|headshot|head of state)\b/i;

const CATEGORY_COVER_VARIANTS = {
  'ai-cong-nghe': ['cat-ai-cong-nghe.svg', 'cat-ai-cong-nghe-b.svg', 'cat-ai-cong-nghe-c.svg'],
  'xu-huong': ['cat-xu-huong.svg', 'cat-xu-huong-b.svg', 'cat-xu-huong-c.svg'],
  'dao-tao-nghe-nghiep': ['cat-dao-tao-nghe-nghiep.svg', 'cat-dao-tao-nghe-nghiep-b.svg', 'cat-dao-tao-nghe-nghiep-c.svg'],
  'kinh-doanh': ['cat-kinh-doanh.svg', 'cat-kinh-doanh-b.svg', 'cat-kinh-doanh-c.svg'],
  'doi-song': ['cat-doi-song.svg', 'cat-doi-song-b.svg', 'cat-doi-song-c.svg'],
  'giai-tri': ['cat-giai-tri.svg', 'cat-giai-tri-b.svg', 'cat-giai-tri-c.svg'],
};

function pickCategoryCover(categorySlug, avoidFile) {
  const variants = CATEGORY_COVER_VARIANTS[categorySlug] || CATEGORY_COVER_VARIANTS['ai-cong-nghe'];
  const pool = avoidFile ? variants.filter((f) => `/images/blog/${f}` !== avoidFile) : variants;
  const choices = pool.length ? pool : variants;
  return `/images/blog/${choices[Math.floor(Math.random() * choices.length)]}`;
}

function isPersonPortrait(title, meta) {
  const text = [title, meta && meta.ObjectName && meta.ObjectName.value, meta && meta.ImageDescription && meta.ImageDescription.value]
    .filter(Boolean)
    .join(' ');
  return PERSON_PORTRAIT_PATTERN.test(text);
}

async function fetchWikimediaInfo(pageid) {
  const url = `https://commons.wikimedia.org/w/api.php?action=query&pageids=${pageid}&prop=imageinfo&iiprop=extmetadata&format=json&origin=*`;
  const res = await fetch(url, { headers: { 'user-agent': 'DinhThiAi-NewsFactory/1.0' } });
  if (!res.ok) return null;
  const data = await res.json();
  const page = data.query && data.query.pages && data.query.pages[pageid];
  if (!page) return null;
  return { title: page.title, meta: (page.imageinfo && page.imageinfo[0] && page.imageinfo[0].extmetadata) || {} };
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function run() {
  await connectDB();

  const posts = await BlogPost.findAll({
    where: { isAutoGenerated: true, coverImageSourceId: { [Op.ne]: null } },
  });

  let flagged = 0;
  let checked = 0;
  for (const post of posts) {
    checked += 1;
    const info = await fetchWikimediaInfo(post.coverImageSourceId);
    await sleep(200);
    if (!info) continue;

    if (!isPersonPortrait(info.title, info.meta)) continue;

    flagged += 1;
    console.log(`>>> PHÁT HIỆN ảnh chân dung không liên quan: "${post.title}" — ảnh: ${info.title}`);

    const oldUrl = post.coverImageUrl;
    const newUrl = pickCategoryCover(post.category);
    const newContent = post.content.replace(/<p class="text-xs text-muted italic">Ảnh:[\s\S]*?<\/p>/, '');
    await post.update({ coverImageUrl: newUrl, coverImageSourceId: null, content: newContent });

    if (oldUrl && oldUrl.startsWith('/images/blog/auto/')) {
      const oldPath = path.join(__dirname, '..', 'public', oldUrl.replace(/^\//, ''));
      fs.unlink(oldPath, () => {});
    }
  }

  console.log(`Xong — đã kiểm tra ${checked} bài, phát hiện và sửa ${flagged} bài dùng ảnh chân dung không liên quan.`);
  process.exit(0);
}

run().catch((err) => {
  console.error('lỗi:', err.message);
  process.exit(1);
});
