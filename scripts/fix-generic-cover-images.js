/**
 * routes/autopost.js trước đây gọi fetchStockImage với specificQuery=null khi
 * tool đăng bài không kèm ảnh — fetchStockImage rơi về từ khoá CHUNG theo
 * chuyên mục (VD "smartphone technology device photo" cho mọi bài AI &
 * Công nghệ), nên nhiều bài liền nhau đều ra ảnh tay cầm điện thoại dù nội
 * dung không liên quan gì (thầy chỉ thẳng ra 3 bài ngày 20/9/2026). Đã sửa
 * autopost.js dùng suggestImageQuery(title) để sinh từ khoá SÁT đúng tiêu đề
 * — script này chạy lại cho các bài GẦN ĐÂY đã lỡ dính ảnh chung chung đó,
 * thay bằng ảnh đúng nội dung hơn. Chỉ thay khi tìm được ảnh KHÁC ảnh hiện
 * tại, không làm bài nào xấu đi.
 *
 * Chạy 1 lần trên máy chủ:
 *   source ~/nodevenv/dinh-thi-ai/20/bin/activate
 *   node scripts/fix-generic-cover-images.js
 */
require('dotenv').config();
const { Op } = require('sequelize');
const connectDB = require('../config/db');
const BlogPost = require('../models/BlogPost');
const { fetchStockImage, suggestImageQuery } = require('../services/newsFactoryService');

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function run() {
  await connectDB();

  // Chỉ quét bài GẦN ĐÂY (7 ngày) đăng qua /api/auto-post — ảnh của các bài
  // này nằm trong public/images/blog/auto/, khác nguồn với ảnh thầy tự tải
  // lên qua trang quản trị (nằm ở /uploads/).
  const posts = await BlogPost.findAll({
    where: {
      isAutoGenerated: true,
      coverImageUrl: { [Op.like]: '/images/blog/auto/%' },
      createdAt: { [Op.gte]: new Date(Date.now() - 7 * 24 * 60 * 60 * 1000) },
    },
    order: [['createdAt', 'DESC']],
  });

  if (!posts.length) {
    console.log('Không có bài nào gần đây cần kiểm tra lại ảnh.');
    process.exit(0);
  }

  const usedImages = await BlogPost.findAll({
    where: { coverImageSourceId: { [Op.ne]: null } },
    attributes: ['coverImageSourceId'],
  });
  const usedPageIds = new Set(usedImages.map((p) => p.coverImageSourceId));

  let upgraded = 0;
  let skipped = 0;
  for (const post of posts) {
    const imageQuery = await suggestImageQuery(post.title);
    if (!imageQuery) {
      console.log(`bỏ qua (Claude không sinh được từ khoá lúc này): ${post.title}`);
      skipped += 1;
      await sleep(1200);
      continue;
    }
    const stockImage = await fetchStockImage(post.category, usedPageIds, imageQuery, post.title);
    if (!stockImage || stockImage.sourceId === post.coverImageSourceId) {
      console.log(`bỏ qua (không tìm được ảnh khác/tốt hơn): ${post.title}`);
      skipped += 1;
      await sleep(1200);
      continue;
    }
    await post.update({ coverImageUrl: stockImage.url, coverImageSourceId: stockImage.sourceId });
    usedPageIds.add(stockImage.sourceId);
    upgraded += 1;
    console.log(`đã đổi ảnh sát nội dung hơn cho: ${post.title} (từ khoá: "${imageQuery}")`);
    await sleep(1200);
  }

  console.log(`Xong — đã đổi ảnh cho ${upgraded} bài, giữ nguyên ${skipped} bài.`);
  process.exit(0);
}

run().catch((err) => {
  console.error('lỗi:', err.message);
  process.exit(1);
});
