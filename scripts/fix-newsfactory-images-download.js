/**
 * Tải về và lưu local cho ảnh của các bài "Nhà máy tin tức AI" đã tạo TRƯỚC
 * KHI newsFactoryService.js được sửa để tự tải ảnh về (trước đó chỉ hotlink
 * trực tiếp từ Wikimedia — dễ vỡ ảnh nếu dịch vụ tạo thumbnail của Wikimedia
 * phản hồi chậm đúng lúc có người load trang).
 *
 * Chạy 1 lần trên máy chủ:
 *   source ~/nodevenv/dinh-thi-ai/20/bin/activate
 *   node scripts/fix-newsfactory-images-download.js
 * Chạy lại lần nữa vẫn an toàn — bài đã có ảnh local rồi thì bị bỏ qua.
 */
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const connectDB = require('../config/db');
const BlogPost = require('../models/BlogPost');

const AUTO_IMAGE_DIR = path.join(__dirname, '..', 'public', 'images', 'blog', 'auto');

async function run() {
  await connectDB();

  const posts = await BlogPost.findAll({
    where: { isAutoGenerated: true },
  });

  let fixed = 0;
  let failed = 0;
  for (const post of posts) {
    if (!post.coverImageUrl || !/^https?:\/\//.test(post.coverImageUrl)) continue; // đã là ảnh local rồi

    try {
      const res = await fetch(post.coverImageUrl);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const ext = /\.png(\?|$)/i.test(post.coverImageUrl) ? 'png' : 'jpg';
      const filename = `${post.coverImageSourceId || post.id}-${Date.now().toString(36)}.${ext}`;
      fs.mkdirSync(AUTO_IMAGE_DIR, { recursive: true });
      const buffer = Buffer.from(await res.arrayBuffer());
      fs.writeFileSync(path.join(AUTO_IMAGE_DIR, filename), buffer);
      await post.update({ coverImageUrl: `/images/blog/auto/${filename}` });
      fixed += 1;
      console.log('đã tải ảnh cho:', post.title);
    } catch (err) {
      failed += 1;
      // Tải lỗi thì chuyển về ảnh SVG dự phòng theo chuyên mục thay vì để vỡ ảnh.
      await post.update({ coverImageUrl: `/images/blog/cat-${post.category}.svg` });
      console.log('tải lỗi, dùng SVG dự phòng cho:', post.title, '-', err.message);
    }
  }

  console.log(`Xong — đã tải ${fixed} ảnh, ${failed} bài chuyển về SVG dự phòng.`);
  process.exit(0);
}

run().catch((err) => {
  console.error('lỗi:', err.message);
  process.exit(1);
});
