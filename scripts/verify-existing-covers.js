/**
 * Xác thực lại ẢNH BÌA HIỆN TẠI (không phải tìm ảnh mới) của toàn bộ bài
 * "Nhà máy tin tức AI" đã đăng, dùng Claude (đọc được ảnh) so với tiêu đề bài
 * — bắt các trường hợp ảnh hoàn toàn lạc đề mà chưa từng qua bước xác thực
 * này (ảnh được lưu từ trước khi có isImageRelevant, hoặc script nâng cấp
 * trước đó không tìm được ảnh mới nên giữ nguyên ảnh cũ mà không tự kiểm tra
 * lại ảnh đang có). Phát hiện thực tế: bài "Robot chó Lynx M20..." bị gắn 1
 * sơ đồ khoa học nhận thức tiếng Nhật hoàn toàn không liên quan.
 *
 * Ảnh không đạt sẽ được chuyển ngay về SVG dự phòng an toàn theo chuyên mục
 * (ưu tiên an toàn — không cố tìm ảnh thay thế tự động trong script này để
 * tránh gọi thêm Wikimedia đang bị giới hạn tốc độ; chạy
 * scripts/upgrade-newsfactory-images-relevance.js sau đó nếu muốn có ảnh
 * thật thay cho SVG).
 *
 * Chạy 1 lần trên máy chủ:
 *   source ~/nodevenv/dinh-thi-ai/20/bin/activate
 *   node scripts/verify-existing-covers.js
 */
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const connectDB = require('../config/db');
const BlogPost = require('../models/BlogPost');
const { isImageRelevant } = require('../services/newsFactoryService');

const CREDIT_PATTERN = /<p class="text-xs text-muted italic">Ảnh:[\s\S]*?<\/p>/;

const CATEGORY_COVER_VARIANTS = {
  'ai-cong-nghe': ['cat-ai-cong-nghe.svg', 'cat-ai-cong-nghe-b.svg', 'cat-ai-cong-nghe-c.svg'],
  'xu-huong': ['cat-xu-huong.svg', 'cat-xu-huong-b.svg', 'cat-xu-huong-c.svg'],
  'dao-tao-nghe-nghiep': ['cat-dao-tao-nghe-nghiep.svg', 'cat-dao-tao-nghe-nghiep-b.svg', 'cat-dao-tao-nghe-nghiep-c.svg'],
  'kinh-doanh': ['cat-kinh-doanh.svg', 'cat-kinh-doanh-b.svg', 'cat-kinh-doanh-c.svg'],
  'doi-song': ['cat-doi-song.svg', 'cat-doi-song-b.svg', 'cat-doi-song-c.svg'],
  'giai-tri': ['cat-giai-tri.svg', 'cat-giai-tri-b.svg', 'cat-giai-tri-c.svg'],
};

function pickCategoryCover(categorySlug) {
  const variants = CATEGORY_COVER_VARIANTS[categorySlug] || CATEGORY_COVER_VARIANTS['ai-cong-nghe'];
  return `/images/blog/${variants[Math.floor(Math.random() * variants.length)]}`;
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function run() {
  await connectDB();

  const posts = await BlogPost.findAll({
    where: { isAutoGenerated: true },
    order: [['createdAt', 'ASC']],
  });

  let checked = 0;
  let fixed = 0;
  for (const post of posts) {
    if (!post.coverImageUrl || !post.coverImageUrl.startsWith('/images/blog/auto/')) continue; // SVG rồi, bỏ qua
    checked += 1;

    const relevant = await isImageRelevant(post.coverImageUrl, post.title);
    await sleep(1000);

    if (relevant) continue;

    console.log(`>>> ẢNH LẠC ĐỀ: "${post.title}" — ${post.coverImageUrl}`);
    const oldUrl = post.coverImageUrl;
    const newUrl = pickCategoryCover(post.category);
    const newContent = post.content.replace(CREDIT_PATTERN, '');
    await post.update({ coverImageUrl: newUrl, coverImageSourceId: null, content: newContent });

    const oldPath = path.join(__dirname, '..', 'public', oldUrl.replace(/^\//, ''));
    fs.unlink(oldPath, () => {});

    fixed += 1;
  }

  console.log(`Xong — đã kiểm tra ${checked} ảnh thật, phát hiện và sửa ${fixed} ảnh lạc đề.`);
  process.exit(0);
}

run().catch((err) => {
  console.error('lỗi:', err.message);
  process.exit(1);
});
