/**
 * Sửa định dạng cho các bài do "Nhà máy tin tức AI" đã tạo TRƯỚC KHI
 * newsFactoryService.js được sửa để tự chuyển markdown -> HTML — những bài
 * này vẫn còn lưu markdown thô (## , **...**, [text](url)) trong content,
 * hiện ra thành chữ thô trên trang thay vì tiêu đề/link thật.
 * Chạy 1 lần trên máy chủ:
 *   source ~/nodevenv/dinh-thi-ai/20/bin/activate
 *   node scripts/fix-newsfactory-post-formatting.js
 * Chạy lại lần nữa vẫn an toàn — bài đã có HTML rồi thì bị bỏ qua.
 */
require('dotenv').config();
const connectDB = require('../config/db');
const BlogPost = require('../models/BlogPost');

function inlineMarkdown(text) {
  return text
    .replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g, '<a href="$2" target="_blank" rel="noopener noreferrer nofollow">$1</a>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
}

function markdownToHtml(markdown) {
  return markdown
    .split(/\n{2,}/)
    .map((block) => block.trim())
    .filter(Boolean)
    .map((block) => {
      const heading = block.match(/^#{2,3}\s+(.+)$/);
      if (heading) return `<h2>${inlineMarkdown(heading[1])}</h2>`;
      return `<p>${inlineMarkdown(block).replace(/\n/g, '<br>')}</p>`;
    })
    .join('\n');
}

async function run() {
  await connectDB();

  const posts = await BlogPost.findAll({ where: { isAutoGenerated: true } });
  let fixed = 0;
  for (const post of posts) {
    const looksLikeRawMarkdown = /^##\s|\*\*[^*]+\*\*|\[[^\]]+\]\(https?:\/\//m.test(post.content) && !/<h2>|<p>|<strong>/.test(post.content);
    if (!looksLikeRawMarkdown) continue;
    await post.update({ content: markdownToHtml(post.content) });
    fixed += 1;
    console.log('đã sửa:', post.title);
  }
  console.log(`Xong — đã sửa ${fixed}/${posts.length} bài tự động.`);
  process.exit(0);
}

run().catch((err) => {
  console.error('lỗi:', err.message);
  process.exit(1);
});
